export function translate(language, key, params = {}) {
  const template = STRINGS[language]?.[key] ?? STRINGS.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ""));
}

const LANGUAGE_KEY = "scamshield.language";

/** The saved language, else Hindi for Hindi browsers, else English. */
export function initialLanguage() {
  let stored = null;
  try {
    stored = localStorage.getItem(LANGUAGE_KEY);
  } catch {
    // Storage can be blocked (private mode, strict settings).
  }
  if (stored === "en" || stored === "hi") return stored;
  return (navigator.language || "").toLowerCase().startsWith("hi") ? "hi" : "en";
}

export function storeLanguage(language) {
  try {
    localStorage.setItem(LANGUAGE_KEY, language);
  } catch {
    // Without storage the choice lasts for this visit only.
  }
}

/** Translate every element marked with data-i18n and update the language buttons. */
export function applyStaticText(language) {
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = translate(language, node.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    node.placeholder = translate(language, node.dataset.i18nPlaceholder);
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((node) => {
    node.setAttribute("aria-label", translate(language, node.dataset.i18nAriaLabel));
  });
  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === language));
  });
}
